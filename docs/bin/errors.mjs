#!/usr/bin/env node
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(import.meta.dirname, "..", "..");
const TABLE = "test/contract/errors.json";
const { message, kinds, codes, failures } = JSON.parse(readFileSync(join(ROOT, TABLE), "utf8"));

const LANGUAGES = [
  { key: "ruby", label: "Ruby" },
  { key: "node", label: "JavaScript" },
  { key: "web", label: "Browser" },
  { key: "python", label: "Python" },
  { key: "go", label: "Go" },
];

const entries = Object.entries(failures);
const quoted = (text) => JSON.stringify(text);
const marked = (text, mark) => text.replaceAll(/\{[a-z_]+\}/g, mark);

function typescript() {
  const lines = entries.map(([key, held]) => {
    const inline = `  ${key}: [${quoted(held.code)}, ${quoted(held.description)}],`;

    if (inline.length <= 80) return inline;

    return `  ${key}: [\n    ${quoted(held.code)},\n    ${quoted(held.description)},\n  ],`;
  });

  return `export const FAILURES = {\n${lines.join("\n")}\n} as const;\n\nexport type Failure = keyof typeof FAILURES;\n`;
}

function python() {
  const lines = entries.map(
    ([key, held]) =>
      `    ${quoted(key)}: (\n        ${quoted(held.code)},\n        ${quoted(marked(held.description, "{}"))},\n    ),`,
  );

  return `FAILURES: dict[str, tuple[str, str]] = {\n${lines.join("\n")}\n}\n`;
}

function go() {
  const width = Math.max(...entries.map(([key]) => key.length + 4));
  const lines = entries.map(([key, held]) => {
    const name = `${quoted(key)}:`.padEnd(width);

    return `\t${name}{${quoted(held.code)}, ${quoted(marked(held.description, "%s"))}},`;
  });

  return `package masks\n\nvar failures = map[string][2]string{\n${lines.join("\n")}\n}\n`;
}

function ruby() {
  const lines = entries.map(
    ([key, held]) => `      ${key}: [ ${quoted(held.code)}, ${quoted(marked(held.description, "%s"))} ]`,
  );

  return `module Masks\n  module Client\n    FAILURES = {\n${lines.join(",\n")}\n    }.freeze\n  end\nend\n`;
}

function cell(text) {
  return String(text).replaceAll("|", "\\|");
}

function described(text) {
  return cell(text).replaceAll(/\{[a-z_]+\}/g, (held) => `\`${held}\``);
}

function row(cells) {
  return `| ${cells.join(" | ")} |`;
}

function table(head, rows) {
  return [row(head), row(head.map(() => "---")), ...rows.map(row)].join("\n");
}

function docs() {
  const means = table(
    ["Kind", "Means", "Code", "Carries"],
    kinds.map((kind) => [`\`${kind.name}\``, cell(kind.meaning), cell(kind.code), kind.fields.map((field) => `\`${field}\``).join(", ")]),
  );

  const names = table(
    ["Kind", ...LANGUAGES.map((language) => language.label)],
    kinds.map((kind) => [`\`${kind.name}\``, ...LANGUAGES.map((language) => (kind.names[language.key] ? `\`${kind.names[language.key]}\`` : "–"))]),
  );

  const listed = table(
    ["Code", "From", "Means"],
    Object.entries(codes).map(([code, held]) => [`\`${code}\``, held.from === "masks" ? "masks" : "the SDK", cell(held.meaning)]),
  );

  const worded = table(
    ["Failure", "Kind", "Code", "Description"],
    entries.map(([key, held]) => [`\`${key}\``, `\`${held.kind}\``, held.code ? `\`${held.code}\`` : "none", described(held.description)]),
  );

  return `---
title: Errors
description: The errors every masks SDK raises, with the kind, the code, and the description each failure gets.
---

Every SDK raises the same error for the same failure. The kinds, the codes, and the descriptions
below come from one table, [\`${TABLE}\`](https://github.com/masksrb/masks/blob/main/${TABLE}),
and each SDK ships a copy generated by \`./dev reference\`. CI fails when a copy or this page drifts
from the table.

Every error's message reads \`${message}\`. A failure the table lists gets the description in the
last table, with the parts in braces filled in.

## Kinds

${means}

Each kind spells its name the way its language does. A dash means the SDK has no such call.

${names}

## Codes

${listed}

## Descriptions

${worded}
`;
}

const OUTPUTS = [
  ["node/src/failures.ts", typescript()],
  ["web/src/failures.ts", typescript()],
  ["python/src/masks/failures.py", python()],
  ["go/failures.go", go()],
  ["client/lib/masks/client/failures.rb", ruby()],
  ["docs/src/content/docs/reference/errors.mdx", docs()],
];

for (const [path, body] of OUTPUTS) {
  writeFileSync(join(ROOT, path), body);
}

console.log(`${entries.length} failures, ${kinds.length} kinds, and ${Object.keys(codes).length} codes written to ${OUTPUTS.length} files`);
